def write_pdfs(reports):
    from playwright.sync_api import sync_playwright
    OUT.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as pw:
        try:
            browser = pw.chromium.launch(channel="chrome")
        except Exception:
            browser = pw.chromium.launch()
        page = browser.new_page()
        for r in reports:
            page.set_content(html_report(r), wait_until="networkidle")
            page.evaluate("document.fonts.ready")
            page.pdf(path=str(OUT / f"{r['slug']}.pdf"), **ek.pdf_options(r["business"], r["question"], f"{r['slug']}.pdf", ds.as_at_text()))
        browser.close()


def write_cards(reports):
    """The 'Example reports' cards on the SME and not-for-profit pages (between the REPORT CARDS markers)."""
    import html as H
    for aud, page in (("sme", "sme.html"), ("nfp", "not-for-profit.html")):
        cards = []
        for r in [x for x in reports if x["audience"] == aud]:
            shows = next((sec["shows"] for b in r["blocks"] for sec in b["sections"] if sec["type"] == "text"), r["intro"])
            first = shows.split(". ")[0].rstrip(".") + "."
            cards.append(f'            <li><h3><a href="report-{r["slug"]}.html">{H.escape(r["question"])}</a></h3>'
                         f'<p>{H.escape(first)}</p><a class="report-open" href="report-{r["slug"]}.html">Open the report &rarr;</a></li>')
        if aud == "sme":
            cards.append('            <li class="report-later"><h3>Will cash cover payroll next month?</h3><p>A 13-week cash forecast built from your bank and '
                         'accounting system, with room for what you expect that the systems don\'t know yet. Coming soon.</p></li>')
        f = REPO / page
        s_ = f.read_text()
        a_, b_ = s_.index("<!-- REPORT CARDS:START -->"), s_.index("<!-- REPORT CARDS:END -->")
        s_ = s_[:a_] + "<!-- REPORT CARDS:START -->\n          <ul class=\"report-cards\">\n" + "\n".join(cards) + "\n          </ul>\n          " + s_[b_:]
        f.write_text(s_)


def publish(reports):
    size = write_js(reports)
    write_pages(reports)
    write_cards(reports)
    for r in reports:
        review = write_xlsx(r)
        print(f"  {r['slug']}.xlsx: " + " | ".join(review))
    write_pdfs(reports)
    print(f"  {len(reports)} report pages, data/reports-data.js {size // 1024} KB")
