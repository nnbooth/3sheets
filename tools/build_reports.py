#!/usr/bin/env python3
"""
build_reports.py — one page per question on the SME and not-for-profit pages.

Writes, from tools/reports.py:
  report-<slug>.html                 the page (header, nav, contact and footer copied from sme.html,
                                     so every page stays the same; the report itself is drawn by script.js)
  data/reports-data.js               what the pages read (each set of workings stored once)
  media/exports/reports/<slug>.xlsx  data as values, every calculation a formula, print-checked
  media/exports/reports/<slug>.pdf   A4, vector charts, header and footer on every page

Run via tools/sample_data.py.
"""

import copy
