def write_pdfs(res):
    from playwright.sync_api import sync_playwright
    EXPORTS.mkdir(parents=True, exist_ok=True)
    with sync_playwright() as p:
        try:
            browser = p.chromium.launch(channel="chrome")
        except Exception:
            browser = p.chromium.launch()
        page = browser.new_page()
        for org in ORDER:
            page.set_content(html_report(org, res[org]), wait_until="networkidle")
            page.evaluate("document.fonts.ready")
            page.pdf(path=str(EXPORTS / f"{org}-sample-statements.pdf"), format="A4", print_background=True)
        browser.close()


def publish():
    res = fm.build()  # runs every check; stops here if anything doesn't add up
    write_dashboard_js(res)
    for org in ORDER:
        write_xlsx(org, res[org])
    write_pdfs(res)
    return csv_tables(res)
