def detail_table(org, v):
    """The granular list behind the statements: (title, head, rows, money columns)."""
    o = v["out"]
    if org == "trades":
        head = ["Month", "Job", "Type", "Description", "Invoiced", "Paid", "Revenue", "Materials", "Subcontractors",
                "Tech hours", "Labour cost", "Gross profit", "Margin %"]
        rows = [[j["month"], j["job"], j["type"], j["description"], j["invoice_date"].isoformat(), j["paid_date"].isoformat(),
                 j["revenue"], j["materials"], j["subcontractors"], j["hours"], j["labour_cost"], j["gross_profit"],
                 round(100 * j["gross_profit"] / j["revenue"], 1)] for j in o["jobs"] if j["month"] in fm.PERIODS]
        rows.sort(key=lambda r: (r[0] != "2026-09", r[2], r[1]))
        return "Jobs, September and August 2026", head, rows
    if org == "services":
        head = ["Month", "Engagement", "Type", "Description", "Hours", "Revenue", "Billed", "Contractors",
                "Consultant time cost", "Contribution", "Margin %"]
        rows = [[x["month"], x["code"], x["type"], x["description"], x["hours"], x["revenue"], x["billed"], x["contractors"],
                 x["allocated_cost"], x["contribution"], round(100 * x["contribution"] / x["revenue"], 1)] for x in o["engagements"]]
        rows.sort(key=lambda r: (r[0] != "2026-09", r[1]))
        return "Client engagements, September and August 2026", head, rows
    head = ["Grant", "Program", "Funder", "Total", "Start", "End", "Received to date", "Spent to date", "Spent Aug", "Spent Sep",
            "Budget to date", "Spend vs budget %", "Still to spend", "Months left"]
    rows = [[g["code"], g["program"], g["funder"], g["total"], g["start"], g["end"], g["received_to_date"], g["spent_to_date"],
             g["spent_aug"], g["spent_sep"], g["budget_to_date"], g["spend_vs_budget_pct"], g["unspent"], g["months_left"]] for g in o["grants"]]
    return "Grants at 30 September 2026", head, rows


def pdf_detail_rows(org, v):
    """Shorter list for the PDF: September only, call-outs rolled into one line."""
    title, head, rows = detail_table(org, v)
    if org == "nfp":
        return title, head, rows
    sep = [r for r in rows if r[0] == "2026-09"]
    if org == "trades":
        calls = [r for r in sep if r[2] == "Call-out"]
        sep = [r for r in sep if r[2] != "Call-out"]
        tot = lambda i: sum(r[i] for r in calls)
        sep.append(["2026-09", "C-09xx", "Call-out", f"{len(calls)} call-outs (each one is in the Excel and CSV)", "", "",
                    tot(6), tot(7), tot(8), tot(9), tot(10), tot(11), round(100 * tot(11) / tot(6), 1)])
        keep = [1, 2, 3, 6, 7, 8, 10, 11, 12]
    else:
        keep = [1, 2, 3, 4, 5, 6, 7, 9, 10]
    return title.replace(", September and August", ", September"), [head[i] for i in keep], [[r[i] for i in keep] for r in sep]


# =============================================================== CSV rows

def csv_tables(res):
    st, kp, asm = [], [], []
    for org in ORDER:
        v = res[org]
        for skey, s in statements(org, v).items():
            for i, rw in enumerate(s["rows"], 1):
                if rw["values"] is None:
                    continue
                for period, val in zip(fm.PERIODS, rw["values"]):
                    st.append([org, skey, s["title"], i, rw["label"], rw["level"], period, val])
        for k in v["fourth"]["kpis"]:
            kp.append([org, k["label"], k["value"], k["sub"]])
        for group, items in v["assumptions"]:
            for item, val in items:
                asm.append([org, group, item, val])
    return {
        "model_statements": ("Home-page dashboard: month-end P&L / income and expenditure, balance sheet and cash flow for the three sample organisations, September 2026 and August 2026, whole dollars. Costs and outflows are negative. level = detail/subtotal/total/key.",
                             ["org", "statement_key", "statement", "line_order", "line", "level", "period", "amount_aud"], st),
        "model_fourth_sheet_kpis": ("Home-page dashboard: the fourth-sheet KPI tiles for September 2026, as displayed.", ["org", "kpi", "value", "comparison"], kp),
        "model_assumptions": ("Home-page dashboard: the assumptions each sample organisation's statements are built from.", ["org", "assumption_group", "assumption", "value"], asm),
    }


# =============================================================== Excel

THIN = Side(style="thin", color=LINE)
DOUBLE = Side(style="double", color=INK)
NUM = '#,##0;(#,##0);"-"'


def xl_statement(ws, title, subtitle, rows, start_row=1):
    ws.cell(start_row, 1, title).font = Font(bold=True, size=14, color=INK)
    ws.cell(start_row + 1, 1, subtitle).font = Font(italic=True, size=9, color=MUTED)
    hr = start_row + 3
    for c, h in enumerate(["$"] + fm.COLUMNS + ["Change"], 1):
        cell = ws.cell(hr, c, h)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=GREEN)
        cell.alignment = Alignment(horizontal="left" if c == 1 else "right")
    r = hr + 1
    for rw in rows:
        a = ws.cell(r, 1, rw["label"])
        if rw["level"] == "heading":
            a.font = Font(bold=True, color=GREEN)
        else:
            for c, val in enumerate(rw["values"] + [f"=B{r}-C{r}"], 2):
                cell = ws.cell(r, c, val)
                cell.number_format = NUM
                cell.alignment = Alignment(horizontal="right")
                if c == 4:
                    cell.font = Font(italic=True, color=MUTED)
            if rw["level"] == "detail":
                a.alignment = Alignment(indent=1)
                a.font = Font(color=MUTED)
            else:
                for c in range(1, 5):
                    ws.cell(r, c).font = Font(bold=True, color=GREEN if rw["level"] == "key" else INK)
                    ws.cell(r, c).border = Border(top=THIN, bottom=DOUBLE if rw["level"] == "key" else None)
                if rw["level"] == "key":
                    for c in range(1, 5):
                        ws.cell(r, c).fill = PatternFill("solid", fgColor=SOFT)
        r += 1
    return r


def write_xlsx(org, v):
    wb = Workbook()
    name = v["model"]["long_name"]
    sub = f"{name} · SAMPLE DATA (invented) · The Fourth Sheet · generated {date.today().isoformat()}"
    f4 = v["fourth"]

    ws = wb.active
    ws.title = "The fourth sheet"
    ws["A1"] = "The fourth sheet: September 2026 vs August 2026"
    ws["A1"].font = Font(bold=True, size=14, color=INK)
    ws["A2"] = sub
    ws["A2"].font = Font(italic=True, size=9, color=MUTED)
    r = 4
    for k in f4["kpis"]:
        ws.cell(r, 1, k["label"]).font = Font(color=MUTED)
        ws.cell(r, 2, k["value"]).font = Font(bold=True, size=12, color=GREEN if k.get("spine") else INK)
        ws.cell(r, 3, k["sub"]).font = Font(size=9, color=MUTED)
        r += 1
    r += 1
    ch = f4["chart"]
    ws.cell(r, 1, ch["title"]).font = Font(bold=True, color=INK)
    for lab, val in zip(ch["labels"], ch["values"]):
        r += 1
        ws.cell(r, 1, lab)
        ws.cell(r, 2, val).number_format = "0.0" if isinstance(val, float) else "0"
    if ch.get("target") is not None:
        r += 1
        ws.cell(r, 1, "Target").font = Font(italic=True, color=MUTED)
        ws.cell(r, 2, ch["target"])
    ws.column_dimensions["A"].width = 44
    for col in "BCD":
        ws.column_dimensions[col].width = 16

    for key, s in statements(org, v).items():
        w = wb.create_sheet(s["tab"].replace("&", "and"))
        xl_statement(w, s["title"], sub, s["rows"])
        w.column_dimensions["A"].width = 46
        for col in "BCD":
            w.column_dimensions[col].width = 14
        w.freeze_panes = "B5"
        w.page_setup.orientation = "portrait"
        w.page_setup.fitToWidth = 1
        w.sheet_properties.pageSetUpPr.fitToPage = True

    title, head, rows = detail_table(org, v)
    w = wb.create_sheet({"trades": "Jobs", "services": "Engagements", "nfp": "Grants"}[org])
    w["A1"] = title
    w["A1"].font = Font(bold=True, size=14, color=INK)
    w["A2"] = sub
    w["A2"].font = Font(italic=True, size=9, color=MUTED)
    for c, h in enumerate(head, 1):
        cell = w.cell(4, c, h)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=GREEN)
        cell.alignment = Alignment(horizontal="left" if isinstance(rows[0][c - 1], str) else "right", wrap_text=True)
        w.column_dimensions[get_column_letter(c)].width = 36 if h in ("Description", "Program", "Funder") else 13
    for r, rw in enumerate(rows, 5):
        for c, val in enumerate(rw, 1):
            cell = w.cell(r, c, val)
            if isinstance(val, (int, float)):
                cell.number_format = "0.0" if "%" in head[c - 1] else ("#,##0.0" if "hours" in head[c - 1].lower() and isinstance(val, float) else NUM)
    w.freeze_panes = "C5"
    w.auto_filter.ref = f"A4:{get_column_letter(len(head))}{len(rows) + 4}"

    w = wb.create_sheet("Assumptions")
    w["A1"] = "Assumptions"
    w["A1"].font = Font(bold=True, size=14, color=INK)
    w["A2"] = sub
    w["A2"].font = Font(italic=True, size=9, color=MUTED)
    r = 4
    for group, items in v["assumptions"]:
        w.cell(r, 1, group).font = Font(bold=True, color=GREEN)
        r += 1
        for item, val in items:
            w.cell(r, 1, item).alignment = Alignment(indent=1, vertical="top")
            w.cell(r, 2, val).alignment = Alignment(wrap_text=True, vertical="top")
            r += 1
        r += 1
    w.cell(r, 1, "Checks (all passed)").font = Font(bold=True, color=GREEN)
    for c in checks(org):
        r += 1
        w.cell(r, 1, "✓ " + c)
    w.column_dimensions["A"].width = 40
    w.column_dimensions["B"].width = 70

    EXPORTS.mkdir(parents=True, exist_ok=True)
    wb.save(EXPORTS / f"{org}-sample-statements.xlsx")


