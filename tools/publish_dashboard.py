        for rw in s["rows"]:
            if rw["values"] is None:
                out.append(f"<tr class=heading><td colspan=3>{esc(rw['label'])}</td></tr>")
            else:
                out.append(f"<tr class={rw['level']}><td>{esc(rw['label'])}</td>" + "".join(f"<td class=n>{fmt(x)}</td>" for x in rw["values"]) + "</tr>")
