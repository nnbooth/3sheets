#!/usr/bin/env python3
"""
publish_dashboard.py — turns the checked financial model (financial_model.py)
into everything the website and your database use:

  dashboard-data.js                       data for the home-page dashboard
  media/exports/<org>-sample-statements.xlsx   formatted Excel workbook
  media/exports/<org>-sample-statements.pdf    A4 PDF report
  (CSV rows for sample-data/ are returned to sample_data.py)

Run via:  python3 tools/sample_data.py   (it calls this)
Needs:    pip install openpyxl playwright   (PDFs use your installed Chrome)
"""

import json
from datetime import date
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

import financial_model as fm

REPO = Path(__file__).resolve().parent.parent
EXPORTS = REPO / "media" / "exports"
ORDER = ["trades", "services", "nfp"]
TOGGLE = {"trades": "SME · trades", "services": "SME · services", "nfp": "Not-for-profit"}
GREEN, DARK, INK, MUTED, SOFT, LINE = "2F7A5D", "1F5A43", "25342A", "5F6F63", "EAF6EE", "DCE8DC"


def statements(org, v):
    nfp = org == "nfp"
    o = v["out"]
    return {
        "pnl": {"tab": "P&L", "title": "Income and expenditure" if nfp else "Profit and loss", "rows": o["pnl"]},
        "bs": {"tab": "Balance sheet", "title": "Balance sheet at 30 June", "rows": o["bsr"]},
        "cf": {"tab": "Cash flow", "title": "Cash flow statement", "rows": o["cfr"]},
    }


def checks(org):
    nfp = org == "nfp"
    return [
        "Every subtotal and total adds up",
        "Balance sheet balances: assets = liabilities + " + ("accumulated funds" if nfp else "equity"),
        "Cash flow ends at the cash in the bank",
        ("Surplus ties to the movement in accumulated funds" if nfp else "Profit ties to retained earnings, after dividends"),
    ]


def export_paths(org):
    return {"xlsx": f"media/exports/{org}-sample-statements.xlsx", "pdf": f"media/exports/{org}-sample-statements.pdf"}


def dashboard_payload(res):
    orgs = []
    for org in ORDER:
        v = res[org]
        f4 = v["fourth"]
        orgs.append({
            "id": org, "toggle": TOGGLE[org], "name": v["model"]["long_name"], "about": v["model"]["about"],
            "columns": fm.FY, "unit": "$'000",
            "statements": statements(org, v),
            "fourth": {"kpis": f4["kpis"], "chart": f4["chart"], "table": f4["table"]},
            "checks": checks(org), "assumptions": v["assumptions"], "exports": export_paths(org),
        })
    return {"generated": date.today().isoformat(), "orgs": orgs}


def write_dashboard_js(res):
    payload = dashboard_payload(res)
    js = ("/* dashboard-data.js — GENERATED by tools/sample_data.py from tools/financial_model.py.\n"
          "   Don't edit by hand: change the assumptions in financial_model.py and re-run.\n"
          "   All figures are invented sample data, in $'000 unless labelled. */\n"
          "window.FOURTH_SHEET_DASHBOARD = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n")
    (REPO / "dashboard-data.js").write_text(js)


# =============================================================== CSV rows

def csv_tables(res):
    st, kp, mo, asm = [], [], [], []
    for org in ORDER:
        v = res[org]
        for skey, s in statements(org, v).items():
            for i, rw in enumerate(s["rows"], 1):
                if rw["values"] is None:
                    continue
                for fy, val in zip(fm.FY, rw["values"]):
                    st.append([org, s["title"], i, rw["label"], rw["level"], fy, val])
        for k in v["fourth"]["kpis"]:
            kp.append([org, k["label"], k["value"], k["sub"]])
        for measure, vals in v["fourth"]["monthly"].items():
            for mth, val in zip(fm.MONTHS, vals):
                mo.append([org, "FY2026", mth, measure, val])
        for group, items in v["assumptions"]:
            for item, val in items:
                asm.append([org, group, item, val])
    return {
        "model_statements": ("Home-page dashboard: P&L / income and expenditure, balance sheet and cash flow for the three sample organisations, FY2026 and FY2025, $'000. Costs and outflows are negative. level = detail/subtotal/total/key.",
                             ["org", "statement", "line_order", "line", "level", "financial_year", "amount_aud_k"], st),
        "model_fourth_sheet_kpis": ("Home-page dashboard: the fourth-sheet KPI tiles, as displayed.", ["org", "kpi", "value", "comparison"], kp),
        "model_monthly": ("Home-page dashboard: monthly drivers behind the fourth-sheet charts, FY2026 (sum to the annual figures).",
                          ["org", "financial_year", "month", "measure", "value"], mo),
        "model_assumptions": ("Home-page dashboard: the assumptions each sample organisation's statements are built from.", ["org", "assumption_group", "assumption", "value"], asm),
    }


# =============================================================== Excel

THIN = Side(style="thin", color=LINE)
DOUBLE = Side(style="double", color=INK)
NUM = '#,##0;(#,##0);"-"'


def xl_statement(ws, title, subtitle, rows, start_row=1):
    ws.cell(start_row, 1, title).font = Font(bold=True, size=14, color=INK)
    ws.cell(start_row + 1, 1, subtitle).font = Font(italic=True, size=9, color=MUTED)
    hr = start_row + 3
    for c, h in enumerate(["$'000"] + fm.FY, 1):
        cell = ws.cell(hr, c, h)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=GREEN)
        cell.alignment = Alignment(horizontal="left" if c == 1 else "right")
    r = hr + 1
    for rw in rows:
        a = ws.cell(r, 1, rw["label"])
        if rw["level"] == "heading":
            a.font = Font(bold=True, color=GREEN)
        else:
            for c, val in enumerate(rw["values"], 2):
                cell = ws.cell(r, c, val)
                cell.number_format = NUM
                cell.alignment = Alignment(horizontal="right")
            if rw["level"] == "detail":
                a.alignment = Alignment(indent=1)
                a.font = Font(color=MUTED)
            else:
                for c in range(1, 4):
                    ws.cell(r, c).font = Font(bold=True, color=GREEN if rw["level"] == "key" else INK)
                    ws.cell(r, c).border = Border(top=THIN, bottom=DOUBLE if rw["level"] == "key" else None)
                if rw["level"] == "key":
                    for c in range(1, 4):
                        ws.cell(r, c).fill = PatternFill("solid", fgColor=SOFT)
        r += 1
    return r


def write_xlsx(org, v):
    wb = Workbook()
    name = v["model"]["long_name"]
    sub = f"{name} · SAMPLE DATA (invented) · The Fourth Sheet · generated {date.today().isoformat()}"
    f4 = v["fourth"]

    ws = wb.active
    ws.title = "The fourth sheet"
    ws["A1"] = "The fourth sheet: the numbers underneath"
    ws["A1"].font = Font(bold=True, size=14, color=INK)
    ws["A2"] = sub
    ws["A2"].font = Font(italic=True, size=9, color=MUTED)
    r = 4
    for k in f4["kpis"]:
        ws.cell(r, 1, k["label"]).font = Font(color=MUTED)
        ws.cell(r, 2, k["value"]).font = Font(bold=True, size=12, color=GREEN if k.get("spine") else INK)
        ws.cell(r, 3, k["sub"]).font = Font(size=9, color=MUTED)
        r += 1
    r += 1
    t = f4["table"]
    ws.cell(r, 1, t["title"]).font = Font(bold=True, color=INK)
    r += 1
    for c, h in enumerate(t["head"], 1):
        cell = ws.cell(r, c, h)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=GREEN)
    for rw in t["rows"] + [t["total"]]:
        r += 1
        for c, val in enumerate(rw, 1):
            cell = ws.cell(r, c, val)
            if isinstance(val, (int, float)):
                cell.number_format = NUM
        if rw is t["total"]:
            for c in range(1, len(rw) + 1):
                ws.cell(r, c).font = Font(bold=True)
                ws.cell(r, c).border = Border(top=THIN, bottom=DOUBLE)
    r += 2
    ch = f4["chart"]
    ws.cell(r, 1, ch["title"]).font = Font(bold=True, color=INK)
    for lab, val in zip(ch["labels"], ch["values"]):
        r += 1
        ws.cell(r, 1, lab)
        ws.cell(r, 2, val).number_format = "0.0" if isinstance(val, float) else "0"
    if ch.get("target") is not None:
        r += 1
        ws.cell(r, 1, "Target").font = Font(italic=True, color=MUTED)
        ws.cell(r, 2, ch["target"])
    ws.column_dimensions["A"].width = 44
    for col in "BCD":
        ws.column_dimensions[col].width = 16

    for key, s in statements(org, v).items():
        w = wb.create_sheet(s["tab"].replace("&", "and"))
        xl_statement(w, s["title"], sub, s["rows"])
        w.column_dimensions["A"].width = 46
        w.column_dimensions["B"].width = w.column_dimensions["C"].width = 14
        w.freeze_panes = "B5"
        w.page_setup.orientation = "portrait"
        w.page_setup.fitToWidth = 1
        w.sheet_properties.pageSetUpPr.fitToPage = True

    w = wb.create_sheet("Assumptions")
    w["A1"] = "Assumptions"
    w["A1"].font = Font(bold=True, size=14, color=INK)
    w["A2"] = sub
    w["A2"].font = Font(italic=True, size=9, color=MUTED)
    r = 4
    for group, items in v["assumptions"]:
        w.cell(r, 1, group).font = Font(bold=True, color=GREEN)
        r += 1
        for item, val in items:
            w.cell(r, 1, item).alignment = Alignment(indent=1, vertical="top")
            w.cell(r, 2, val).alignment = Alignment(wrap_text=True, vertical="top")
            r += 1
        r += 1
    w.cell(r, 1, "Checks (all passed)").font = Font(bold=True, color=GREEN)
    for c in checks(org):
        r += 1
        w.cell(r, 1, "✓ " + c)
    w.column_dimensions["A"].width = 40
    w.column_dimensions["B"].width = 70

    EXPORTS.mkdir(parents=True, exist_ok=True)
    wb.save(EXPORTS / f"{org}-sample-statements.xlsx")


