#!/usr/bin/env python3
"""
publish_dashboard.py — turns the checked financial model (financial_model.py)
into everything the website and your database use:

  dashboard-data.js                       data for the home-page dashboard
  media/exports/<org>-sample-statements.xlsx   formatted Excel workbook
  media/exports/<org>-sample-statements.pdf    A4 PDF report
  (CSV rows for the OneDrive data folder are returned to sample_data.py)

Run via:  python3 tools/sample_data.py   (it calls this)
Needs:    pip install openpyxl playwright   (PDFs use your installed Chrome)
"""

import json
from datetime import date
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

import financial_model as fm

REPO = Path(__file__).resolve().parent.parent
EXPORTS = REPO / "media" / "exports"
ORDER = ["trades", "services", "nfp"]
TOGGLE = {"trades": "SME · trades", "services": "SME · services", "nfp": "Not-for-profit"}
GREEN, DARK, INK, MUTED, SOFT, LINE = "2F7A5D", "1F5A43", "25342A", "5F6F63", "EAF6EE", "DCE8DC"


def statements(org, v):
    nfp = org == "nfp"
    o = v["out"]
    return {
        "pnl": {"tab": "P&L", "title": ("Income and expenditure" if nfp else "Profit and loss") + ", September 2026", "rows": o["pnl"]},
        "bs": {"tab": "Balance sheet", "title": "Balance sheet at 30 September 2026", "rows": o["bsr"]},
        "cf": {"tab": "Cash flow", "title": "Cash flow, September 2026", "rows": o["cfr"]},
    }


def checks(org):
    nfp = org == "nfp"
    detail = {
        "trades": ["Every job's revenue, materials and subcontractors add up to the P&L",
                   "Trade debtors equal the invoices still unpaid at month end"],
        "services": ["Every engagement's revenue adds up to the P&L",
                     "Work in progress equals unbilled project time; debtors equal unpaid invoices"],
        "nfp": ["Grant income equals what was spent on each grant",
                "Unspent grants equal instalments received less income recognised"],
    }[org]
    return [
        "Every subtotal and total adds up",
        "Balance sheet balances: assets = liabilities + " + ("accumulated funds" if nfp else "equity"),
        "Cash flow ends at the cash in the bank",
        ("Surplus ties to the movement in accumulated funds" if nfp else "Profit ties to the movement in retained earnings"),
    ] + detail


def export_paths(org):
    return {"xlsx": f"media/exports/{org}-sample-statements.xlsx", "pdf": f"media/exports/{org}-sample-statements.pdf"}


def dashboard_payload(res):
    orgs = []
    for org in ORDER:
        v = res[org]
        f4 = v["fourth"]
        orgs.append({
            "id": org, "toggle": TOGGLE[org], "name": v["model"]["long_name"], "about": v["model"]["about"],
            "columns": fm.COLUMNS, "unit": "$",
            "statements": statements(org, v),
            "fourth": {"kpis": f4["kpis"], "chart": f4["chart"]},
            "checks": checks(org), "assumptions": v["assumptions"], "exports": export_paths(org),
        })
    return {"generated": date.today().isoformat(), "orgs": orgs}


def write_dashboard_js(res):
    payload = dashboard_payload(res)
    js = ("/* dashboard-data.js — GENERATED by tools/sample_data.py from tools/financial_model.py.\n"
          "   Don't edit by hand: change the assumptions in financial_model.py and re-run.\n"
          "   All figures are invented sample data, in whole dollars: September 2026 vs August 2026. */\n"
          "window.FOURTH_SHEET_DASHBOARD = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n")
    (REPO / "dashboard-data.js").write_text(js)


